"""Reproduce every number quoted in the README. Writes benchmarks/RESULTS.md.

python benchmarks/run_benchmarks.py            # full run (~10 min)
python benchmarks/run_benchmarks.py --quick    # smoke run (~1 min)
"""

from __future__ import annotations

import argparse
import platform
import socket
import statistics
import time
from pathlib import Path

import numpy as np

from ai_nic_perf_profiler.analysis import analyze
from ai_nic_perf_profiler.collectors import EthtoolCollector, NetdevSysfsCollector, RdmaSysfsCollector
from ai_nic_perf_profiler.evaluate import evaluate, multi_fault_markdown, sweep, sweep_markdown, to_markdown
from ai_nic_perf_profiler.sim import MULTI_FAULTS, SINGLE_FAULTS, SimConfig, simulate
from ai_nic_perf_profiler.sim.cluster import NUISANCES


def collector_overhead(n: int = 200) -> str:
    host = socket.gethostname()
    rows = ["| collector | endpoints | counters/endpoint | median read (µs) | p99 read (µs) |", "|---|---:|---:|---:|---:|"]
    for c in (NetdevSysfsCollector(host), RdmaSysfsCollector(host)):
        snaps = c.collect()
        if not snaps:
            rows.append(f"| {c.name} | 0 | - | - | - |")
            continue
        times = []
        for _ in range(n):
            t0 = time.perf_counter()
            c.collect()
            times.append((time.perf_counter() - t0) * 1e6)
        times.sort()
        per_ep = statistics.mean(len(s.counters) for s in snaps)
        rows.append(f"| {c.name} | {len(snaps)} | {per_ep:.0f} | {statistics.median(times):.0f} | {times[int(0.99 * len(times)) - 1]:.0f} |")
    return "\n".join(rows)


def ethtool_read_paths(n: int = 200) -> str:
    """Per-interface read cost of the two ethtool paths on this machine's interfaces."""
    host = socket.gethostname()
    rows = ["| read path | interface | counters | median read (µs) | p99 read (µs) |", "|---|---|---:|---:|---:|"]
    ifaces = [name for _, name in socket.if_nameindex() if name != "lo"]
    for backend in ("ioctl", "exec"):
        measured = False
        for iface in ifaces:
            c = EthtoolCollector(host, [iface], backend=backend)  # type: ignore[arg-type]
            raw = c.read_raw(iface)
            if not raw:
                c.close()
                continue
            times = []
            for _ in range(n):
                t0 = time.perf_counter()
                c.read_raw(iface)
                times.append((time.perf_counter() - t0) * 1e6)
            c.close()
            times.sort()
            label = "SIOCETHTOOL ioctl (in-process)" if backend == "ioctl" else "`ethtool -S` (fork+exec)"
            rows.append(f"| {label} | {iface} | {len(raw)} | {statistics.median(times):.0f} | {times[int(0.99 * len(times)) - 1]:.0f} |")
            measured = True
            break
        if not measured:
            rows.append(f"| {backend} | - | - | - | - |")
    return "\n".join(rows)


def adversarial_ablation(seeds: int) -> str:
    rows = ["| nuisances enabled | healthy false positives | top-1 cause (8 single faults) | culprit recall |", "|---|---:|---:|---:|"]
    combos: list[tuple[str, ...]] = [(n,) for n in NUISANCES] + [NUISANCES]
    for combo in combos:
        summaries = evaluate(seeds=seeds, sim=SimConfig(adversarial=True, nuisances=combo))
        healthy = next(s for s in summaries if s.scenario == "healthy")
        faults = [s for s in summaries if s.scenario in SINGLE_FAULTS]
        top1 = np.mean([t.top1 for s in faults for t in s.trials])
        recalls = [t.recall for s in faults for t in s.trials if t.recall is not None]
        rows.append(f"| {' + '.join(combo)} | {healthy.detect_rate:.0%} | {top1:.0%} | {np.mean(recalls) if recalls else 0:.0%} |")
    return "\n".join(rows)


def scaling(configs: list[tuple[int, int]], steps: int) -> str:
    rows = ["| hosts x NICs | ranks | steps | snapshots | analyze (s) | per (step x rank) (µs) |", "|---|---:|---:|---:|---:|---:|"]
    for hosts, nics in configs:
        cfg = SimConfig(hosts=hosts, nics_per_host=nics, hosts_per_leaf=max(1, hosts // 4), steps=steps, fault_start=steps // 2, fault_end=steps * 5 // 6)
        result = simulate("pfc_storm", cfg)
        t0 = time.perf_counter()
        analyze(result.snapshots, result.steps, result.topology)
        dt = time.perf_counter() - t0
        ranks = hosts * nics
        rows.append(f"| {hosts} x {nics} | {ranks} | {steps} | {len(result.snapshots):,} | {dt:.2f} | {dt / (ranks * steps) * 1e6:.0f} |")
    return "\n".join(rows)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--out", default=str(Path(__file__).with_name("RESULTS.md")))
    args = ap.parse_args()
    seeds, sweep_seeds = (2, 1) if args.quick else (10, 5)
    started = time.time()

    sections = [
        "# Benchmark results",
        "",
        f"Generated by `benchmarks/run_benchmarks.py` on {platform.platform()}, Python {platform.python_version()}.",
        "**Every accuracy number below is a simulator result, not a hardware result.** The simulator and the diagnosis rules encode "
        "the same domain model, so §1-§4 measure *pipeline consistency* (alignment, baselining, decomposition and localisation "
        "under noise), not real-world accuracy. §1b and §1c are the parts designed to break that circularity. No hardware results "
        "exist yet; see the hardware validation plan in docs/methodology.md.",
        "",
        f"## 1. Pipeline consistency: single faults at full severity, simulator ({seeds} seeds per scenario)",
        "",
        "Default sim: 4 hosts x 4 NICs (16 ranks), 2 leaves, 400G, 240 steps, 100 ms counter sampling, 1% step jitter, host clock skew up to ±5 ms, one counter reset and checkpoint spikes per run.",
        "",
        to_markdown(evaluate(seeds=seeds)),
        "",
        f"## 1b. Two concurrent faults, simulator ({seeds} seeds per scenario)",
        "",
        "Two faults on disjoint hosts with the same onset. The first-named fault is the slower bottleneck and sets the step time. "
        "*top-1 = bottleneck* asks whether the primary diagnosis names it; *secondary found* asks whether the masked fault is listed "
        "(primary or secondary suspect) with a correct culprit rank. Their features rise together, so the regression cannot tell "
        "from timing which one is the bottleneck: expect top-1 near chance and both found near 100%.",
        "",
        multi_fault_markdown(evaluate(list(MULTI_FAULTS), seeds=seeds)),
        "",
        f"## 1c. Adversarial mode, simulator ({seeds} seeds per scenario)",
        "",
        "Same scenarios with nuisances the rules were not written around (`SimConfig(adversarial=True)`): heavy-tailed ECN baseline with bursts, "
        "background tenants on two NICs, and a decoy port whose FEC/CRC/sequence counters rise during the fault window without "
        "slowing anything. Reported separately from §1 on purpose.",
        "",
        to_markdown(evaluate(seeds=seeds, sim=SimConfig(adversarial=True))),
        "",
        f"Ablation, one nuisance at a time ({max(2, seeds // 2)} seeds):",
        "",
        adversarial_ablation(max(2, seeds // 2)),
        "",
        f"## 2. Same, with step events logged on rank 0 only ({max(2, seeds // 2)} seeds)",
        "",
        "Other ranks' windows are inferred through per-host clock offsets.",
        "",
        to_markdown(evaluate(seeds=max(2, seeds // 2), sim=SimConfig(steps_rank0_only=True))),
        "",
        f"## 3. Sensitivity: fault severity sweep ({sweep_seeds} seeds x 8 fault scenarios per row)",
        "",
        "How small a slowdown can be detected and correctly attributed?",
        "",
        sweep_markdown("severity", sweep("severity", [0.1, 0.2, 0.35, 0.5, 0.75, 1.0], seeds=sweep_seeds)),
        "",
        f"## 4. Sensitivity: counter sampling interval ({sweep_seeds} seeds x 8 fault scenarios per row, baseline step ≈ 0.39 s)",
        "",
        sweep_markdown("sample_interval_s", sweep("sample_interval_s", [0.05, 0.1, 0.2, 0.4, 0.8, 1.6], seeds=sweep_seeds)),
        "",
        "## 5. Analysis cost vs cluster size (single process, pfc_storm)",
        "",
        scaling([(4, 4), (16, 8), (64, 8)] if not args.quick else [(4, 4), (8, 8)], steps=120),
        "",
        "## 6. Collector read cost on this machine",
        "",
        "Measured on the benchmark machine, which has **no RDMA devices** (hence 0 endpoints for rdma_sysfs). Real mlx5 read costs are hardware plan item H9.",
        "",
        collector_overhead(50 if args.quick else 500),
        "",
        "### ethtool read paths (B12)",
        "",
        "The same driver statistics read two ways on this machine's interfaces (not mlx5; counter counts differ by driver).",
        "",
        ethtool_read_paths(50 if args.quick else 500),
        "",
        f"_Total benchmark wall time: {time.time() - started:.0f} s._",
        "",
    ]
    Path(args.out).write_text("\n".join(sections))
    print("\n".join(sections))


if __name__ == "__main__":
    main()
