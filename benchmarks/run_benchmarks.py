"""Reproduce every number quoted in the README. Writes benchmarks/RESULTS.md.

python benchmarks/run_benchmarks.py            # full run (~10 min)
python benchmarks/run_benchmarks.py --quick    # smoke run (~1 min)
"""

from __future__ import annotations

import argparse
import platform
import socket
import statistics
import time
from pathlib import Path

from ai_nic_perf_profiler.analysis import analyze
from ai_nic_perf_profiler.collectors import NetdevSysfsCollector, RdmaSysfsCollector
from ai_nic_perf_profiler.evaluate import evaluate, sweep, sweep_markdown, to_markdown
from ai_nic_perf_profiler.sim import SimConfig, simulate


def collector_overhead(n: int = 200) -> str:
    host = socket.gethostname()
    rows = ["| collector | endpoints | counters/endpoint | median read (µs) | p99 read (µs) |", "|---|---:|---:|---:|---:|"]
    for c in (NetdevSysfsCollector(host), RdmaSysfsCollector(host)):
        snaps = c.collect()
        if not snaps:
            rows.append(f"| {c.name} | 0 | - | - | - |")
            continue
        times = []
        for _ in range(n):
            t0 = time.perf_counter()
            c.collect()
            times.append((time.perf_counter() - t0) * 1e6)
        times.sort()
        per_ep = statistics.mean(len(s.counters) for s in snaps)
        rows.append(f"| {c.name} | {len(snaps)} | {per_ep:.0f} | {statistics.median(times):.0f} | {times[int(0.99 * len(times)) - 1]:.0f} |")
    return "\n".join(rows)


def scaling(configs: list[tuple[int, int]], steps: int) -> str:
    rows = ["| hosts x NICs | ranks | steps | snapshots | analyze (s) | per (step x rank) (µs) |", "|---|---:|---:|---:|---:|---:|"]
    for hosts, nics in configs:
        cfg = SimConfig(hosts=hosts, nics_per_host=nics, hosts_per_leaf=max(1, hosts // 4), steps=steps, fault_start=steps // 2, fault_end=steps * 5 // 6)
        result = simulate("pfc_storm", cfg)
        t0 = time.perf_counter()
        analyze(result.snapshots, result.steps, result.topology)
        dt = time.perf_counter() - t0
        ranks = hosts * nics
        rows.append(f"| {hosts} x {nics} | {ranks} | {steps} | {len(result.snapshots):,} | {dt:.2f} | {dt / (ranks * steps) * 1e6:.0f} |")
    return "\n".join(rows)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--out", default=str(Path(__file__).with_name("RESULTS.md")))
    args = ap.parse_args()
    seeds, sweep_seeds = (2, 1) if args.quick else (10, 5)
    started = time.time()

    sections = [
        "# Benchmark results",
        "",
        f"Generated by `benchmarks/run_benchmarks.py` on {platform.platform()}, Python {platform.python_version()}.",
        "All accuracy numbers come from the fault-injection simulator (`nicprof simulate`), **not production hardware**; see docs/methodology.md for what that does and doesn't validate.",
        "",
        f"## 1. Attribution accuracy at full fault severity ({seeds} seeds per scenario)",
        "",
        "Default sim: 4 hosts x 4 NICs (16 ranks), 2 leaves, 400G, 240 steps, 100 ms counter sampling, 1% step jitter, host clock skew up to ±5 ms, one counter reset and checkpoint spikes per run.",
        "",
        to_markdown(evaluate(seeds=seeds)),
        "",
        f"## 2. Same, with step events logged on rank 0 only ({max(2, seeds // 2)} seeds)",
        "",
        "Other ranks' windows are inferred through per-host clock offsets.",
        "",
        to_markdown(evaluate(seeds=max(2, seeds // 2), sim=SimConfig(steps_rank0_only=True))),
        "",
        f"## 3. Sensitivity: fault severity sweep ({sweep_seeds} seeds x 8 fault scenarios per row)",
        "",
        "How small a slowdown can be detected and correctly attributed?",
        "",
        sweep_markdown("severity", sweep("severity", [0.1, 0.2, 0.35, 0.5, 0.75, 1.0], seeds=sweep_seeds)),
        "",
        f"## 4. Sensitivity: counter sampling interval ({sweep_seeds} seeds x 8 fault scenarios per row, baseline step ≈ 0.39 s)",
        "",
        sweep_markdown("sample_interval_s", sweep("sample_interval_s", [0.05, 0.1, 0.2, 0.4, 0.8, 1.6], seeds=sweep_seeds)),
        "",
        "## 5. Analysis cost vs cluster size (single process, pfc_storm)",
        "",
        scaling([(4, 4), (16, 8), (64, 8)] if not args.quick else [(4, 4), (8, 8)], steps=120),
        "",
        "## 6. Collector read cost on this machine",
        "",
        collector_overhead(50 if args.quick else 500),
        "",
        f"_Total benchmark wall time: {time.time() - started:.0f} s._",
        "",
    ]
    Path(args.out).write_text("\n".join(sections))
    print("\n".join(sections))


if __name__ == "__main__":
    main()
